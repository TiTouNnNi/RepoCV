def ave_distance(G):
    distance = G.getIntegerProperty('distance')
    tot_dist = 0.0
    for n in G.getNodes():
        tlp.maxDistance(G, n, distance, tlp.EDGE_TYPE.UNDIRECTED)
        tot_dist += np.sum([distance[m] for m in G.getNodes() if
        distance[m] != float('inf')])/(G.numberOfNodes() - 1)
    return tot_dist / G.numberOfNodes()

