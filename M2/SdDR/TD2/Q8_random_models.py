def diametre(graph):
    """
    Compute the diameter of a graph.
    """
    params = tlp.getDefaultPluginParameters('Eccentricity')
    params['norm'] = False
    eccentricity = graph.getDoubleProperty('Eccentricity')
    graph.applyDoubleAlgorithm('Eccentricity', eccentricity, params)
    return max([eccentricity[n] for n in graph.getNodes()])

def ave_stddev(nb_trials, N, p):
    mean = 0
    stddev = 0
    for _ in range(nb_trials):
        G = Erdos_Renyi(N, p)
        d = diametre(G)
        mean += d
        stddev += d**2
    mean /= nb_trials
    stddev = np.sqrt(stddev/nb_trials - mean**2)
    return mean, stddev

def z_score(G, nb_trials):
    mean, stddev = ave_stddev(nb_trials, G.numberOfNodes(), p_estimator(G))
    d = diametre(G)
    return (d - mean) / stddev

