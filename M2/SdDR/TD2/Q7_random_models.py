def poisson(lamb, k):
    """
    Compute the Poisson probability of observing k events given a mean rate of lambda.
    """
    return (lamb ** k) * np.exp(-lamb) / math.factorial(k)

def distance_KS(dist1, dist2):
    """
    Compute the Kolmogorov-Smirnov distance between two distributions.
    """
    cdf1 = np.cumsum(dist1) / np.sum(dist1)
    cdf2 = np.cumsum(dist2) / np.sum(dist2)
    return np.max(np.abs(cdf1 - cdf2))

def dist_degrees(graph):
    """
    Compute the degree distribution of a graph.
    """
    degrees = [graph.deg(node) for node in graph.getNodes()]
    max_degree = max(degrees)
    dist = np.zeros(max_degree + 1)
    for degree in degrees:
        dist[degree] += 1
    return dist / np.sum(dist)

def dist_KS_graphes(graph1, graph2):
    d1 = dist_degrees(graph1)
    d2 = dist_degrees(graph2)
    if len(d1) < len(d2):
        d1 = np.pad(d1, (0, len(d2) - len(d1)), 'constant')
    elif len(d2) < len(d1):
        d2 = np.pad(d2, (0, len(d1) - len(d2)), 'constant')
    return distance_KS(d1, d2)

def dist_KS_theo(graph):
    """
    Compute the Kolmogorov-Smirnov distance between the degree distribution of a graph and the theoretical Poisson distribution.
    """
    N = graph.numberOfNodes()
    degrees = [graph.deg(node) for node in graph.getNodes()]
    lambda_ = np.mean(degrees)
    max_degree = max(degrees)
    dist_theo = np.array([poisson(lambda_, k) for k in range(max_degree + 1)])
    dist_theo_cumul = np.cumsum(dist_theo)
    dist_graph = dist_degrees(graph)
    return distance_KS(dist_graph, dist_theo_cumul)

def p_estimator(graph):
    """
    Estimate the probability p of having an edge between two vertices in a graph.
    """
    N = graph.numberOfNodes()
    M = graph.numberOfEdges()
    return 2 * M / (N * (N - 1))

def p_value(nb_trials, G):
    """
    Compute the p-value of a graph G by
    comparing its distance to the theoretical model to that
    of random graphs generated by the Erdős-Rényi model.
    """
    dist_G_theo = dist_KS_theo(G)
    distances = []
    for _ in range(nb_trials):
        G_random = Erdos_Renyi(G.numberOfNodes(), p_estimator(G))
        distances.append(dist_KS_theo(G_random))
    dist_greater_than_theo = list(filter(lambda x: x > dist_G_theo, distances))
    return len(dist_greater_than_theo)/len(distances)
